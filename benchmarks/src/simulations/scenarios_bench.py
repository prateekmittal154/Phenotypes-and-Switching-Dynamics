"""Ground-truth scenario generator for the cross-method benchmark.

Produces, for each replicate, a package that every method can consume:

  tree_true.nwk      true sampled genealogy T1, branch lengths = generations elapsed
  tree_unit.nwk      same topology, every edge length 1 (the "unit edge" convention)
  tree_recon.nwk     tree reconstructed from simulated barcodes (T3), unit edges
  states.csv         per-leaf binary state, continuous trait, clone id
  truth.json         the generating parameters

Scenarios S1-S8 follow the benchmark brief. The continuous trait is generated by an
Ornstein-Uhlenbeck process on the same genealogy so that SCOUT has a native-format input
rather than a binary variable it was never designed for.

Usage: python -I scenarios_bench.py <studyd_src> <outdir> <scenario> <n_reps> <seed0>
"""
import os, sys, json
import numpy as np

STUDYD = sys.argv[1]
sys.path.insert(0, STUDYD)
from src.branching.recorder import (simulate_genealogy, induced_subtree, record_barcodes,
                                    reconstruct)

OUT = sys.argv[2]
SCEN = sys.argv[3]
NREP = int(sys.argv[4])
SEED0 = int(sys.argv[5])

N_GEN = 11          # generations of synchronous division
N_CLONES = 12       # founder clones
N_LEAVES = 576     # cells sampled per replicate (12 clones x 48)
N_SITES = 10        # recorder target sites
MU = 0.12           # per-site editing rate per generation
N_ALLELES = 12


# ----------------------------------------------------------------- state processes
def evolve_binary(parent, rng, pi, k, elen=None):
    """Two-state CTMC down a genealogy. elen gives per-edge elapsed time (default 1)."""
    st = np.empty(len(parent), int)
    st[0] = int(rng.random() < pi)
    for i in range(1, len(parent)):
        t = 1.0 if elen is None else float(elen[i])
        E = np.exp(-k * t)
        p = st[parent[i]]
        up = pi * (1 - E) if p == 0 else pi + (1 - pi) * E
        st[i] = int(rng.random() < up)
    return st


def evolve_ou(parent, rng, theta, alpha, sigma, elen=None, x0=None):
    """Ornstein-Uhlenbeck trait down the genealogy. Stationary var = sigma^2/(2 alpha)."""
    x = np.empty(len(parent), float)
    sd0 = sigma / np.sqrt(2 * alpha) if alpha > 0 else sigma
    x[0] = theta + rng.normal(0, sd0) if x0 is None else x0
    for i in range(1, len(parent)):
        t = 1.0 if elen is None else float(elen[i])
        e = np.exp(-alpha * t)
        m = theta + (x[parent[i]] - theta) * e
        v = (sigma ** 2) * (1 - e ** 2) / (2 * alpha) if alpha > 0 else (sigma ** 2) * t
        x[i] = m + rng.normal(0, np.sqrt(max(v, 1e-12)))
    return x


# ----------------------------------------------------------------- newick writing
def to_newick(parent, elen, labels):
    """Write a parent-array tree to Newick. labels[i] is the tip label or None for internal."""
    n = len(parent)
    kids = {}
    for i in range(n):
        if parent[i] >= 0:
            kids.setdefault(parent[i], []).append(i)
    root = int(np.where(np.asarray(parent) < 0)[0][0])

    def rec(v):
        if v not in kids:
            return f"{labels[v]}:{max(elen[v], 1e-6):.6f}"
        inner = ",".join(rec(c) for c in kids[v])
        bl = 0.0 if v == root else max(elen[v], 1e-6)
        return f"({inner}):{bl:.6f}"

    return rec(root) + ";"


def collapse_to_binary_labels(parent, elen, keep_order):
    """Relabel leaves cell_0..cell_{m-1} in the given order; internal nodes unlabelled."""
    labels = [None] * len(parent)
    for j, v in enumerate(keep_order):
        labels[v] = f"cell_{j}"
    return labels


# ----------------------------------------------------------------- one replicate
def one_rep(scen, rng):
    """Returns dict with trees, states and the generating truth for one replicate."""
    bott_at = bott_size = None
    clone_bias = None

    if scen == "S6":                      # founder bottleneck
        bott_at, bott_size = 4, 6
    if scen == "S7":                      # unequal clonal expansion
        # founders differ in division probability; implemented via per-node bias on founder identity
        bias = rng.uniform(0.55, 1.0, N_CLONES)
    # genealogy per clone, then pooled
    per_clone = max(8, N_LEAVES // N_CLONES)

    clone_trees = []
    truth_rows = []
    for c in range(N_CLONES):
        cb = None
        if scen == "S7":
            cb = (lambda v, b=bias[c]: b)
        par, gen, live = simulate_genealogy(N_GEN, rng, p_death=0.0, clone_bias=cb,
                                            bottleneck_at=bott_at, bottleneck_size=bott_size)
        if len(live) < 4:
            return None
        take = rng.choice(live, min(per_clone, len(live)), replace=False)
        sub_par, sub_elen, leafmap, _order = induced_subtree(par, take)
        # leafmap: {new_node_index -> original cell index}
        leaf_idx = sorted(leafmap.keys())
        orig_cells = np.array([leafmap[i] for i in leaf_idx], int)

        # ---- clone-level generating parameters
        if scen == "S1":        # stable-state selection: occupancy differs, almost no switching
            pi_c, k_c = rng.uniform(0.12, 0.88), 0.02
        elif scen == "S2":      # equal occupancy, heterogeneous rate
            pi_c, k_c = 0.5, float(np.exp(rng.uniform(np.log(0.05), np.log(2.0))))
        elif scen == "S3":      # heterogeneous occupancy, equal rate
            pi_c, k_c = rng.uniform(0.15, 0.85), 0.3
        elif scen == "S4":      # joint
            pi_c = rng.uniform(0.15, 0.85)
            k_c = float(np.exp(rng.uniform(np.log(0.05), np.log(2.0))))
        elif scen in ("S5", "S6", "S7", "S8"):
            pi_c, k_c = rng.uniform(0.2, 0.8), 0.3
        else:
            raise ValueError(scen)

        # ---- states on the FULL genealogy, then restricted to sampled leaves
        if scen == "S5":
            # environmental induction: switching rate rises in later generations for every clone
            elen_full = np.ones(len(par))
            k_eff = np.where(gen > N_GEN // 2, k_c * 4.0, k_c)
            st = np.empty(len(par), int)
            st[0] = int(rng.random() < pi_c)
            for i in range(1, len(par)):
                E = np.exp(-k_eff[i])
                p = st[par[i]]
                up = pi_c * (1 - E) if p == 0 else pi_c + (1 - pi_c) * E
                st[i] = int(rng.random() < up)
        else:
            st = evolve_binary(par, rng, pi_c, k_c)

        # continuous OU trait: clone optimum theta_c maps occupancy, alpha maps switching
        theta_c = 2.0 * (pi_c - 0.5)
        alpha_c = k_c
        xt = evolve_ou(par, rng, theta_c, max(alpha_c, 1e-3), sigma=1.0)

        leaf_state = st[orig_cells]
        leaf_trait = xt[orig_cells]

        if scen == "S8":        # observation misspecification: phenotype measurement error
            flip = rng.random(len(leaf_state)) < 0.10
            leaf_state = np.where(flip, 1 - leaf_state, leaf_state)
            leaf_trait = leaf_trait + rng.normal(0, 0.5, len(leaf_trait))

        clone_trees.append(dict(parent=sub_par, elen=sub_elen, leaf_idx=leaf_idx,
                                state=leaf_state, trait=leaf_trait, clone=c))
        truth_rows.append(dict(clone=c, pi=float(pi_c), k=float(k_c),
                               theta=float(theta_c), alpha=float(max(alpha_c, 1e-3))))
    return clone_trees, truth_rows


def graft(clone_trees):
    """Join per-clone subtrees under a single deep root so one Newick holds all clones."""
    parent, elen, leaf_rows = [-1], [0.0], []
    offsets = []
    for ct in clone_trees:
        off = len(parent)
        offsets.append(off)
        sp, se = ct["parent"], ct["elen"]
        croot = int(np.where(np.asarray(sp) < 0)[0][0])
        for i in range(len(sp)):
            parent.append(off + sp[i] if sp[i] >= 0 else 0)
            elen.append(float(se[i]) if sp[i] >= 0 else 40.0)   # long stem separates clones
        for i in ct["leaf_idx"]:
            leaf_rows.append((off + i, ct["clone"]))
        _ = croot
    return np.array(parent), np.array(elen), leaf_rows, offsets


def main():
    os.makedirs(OUT, exist_ok=True)
    made = 0
    rep = 0
    while made < NREP and rep < NREP * 5:
        rng = np.random.default_rng(SEED0 + rep)
        rep += 1
        got = one_rep(SCEN, rng)
        if got is None:
            continue
        clone_trees, truth_rows = got
        parent, elen, leaf_rows, offsets = graft(clone_trees)

        # assemble leaf-level tables in a stable order
        leaf_nodes, leaf_clone, leaf_state, leaf_trait = [], [], [], []
        for ct, off in zip(clone_trees, offsets):
            for li, i in enumerate(ct["leaf_idx"]):
                leaf_nodes.append(off + i)
                leaf_clone.append(ct["clone"])
                leaf_state.append(int(ct["state"][li]))
                leaf_trait.append(float(ct["trait"][li]))

        labels = [None] * len(parent)
        for j, v in enumerate(leaf_nodes):
            labels[v] = f"cell_{j}"

        d = os.path.join(OUT, f"{SCEN}_rep{made:03d}")
        os.makedirs(d, exist_ok=True)

        with open(os.path.join(d, "tree_true.nwk"), "w") as f:
            f.write(to_newick(parent, elen, labels) + "\n")
        with open(os.path.join(d, "tree_unit.nwk"), "w") as f:
            f.write(to_newick(parent, np.ones(len(parent)), labels) + "\n")

        import csv
        with open(os.path.join(d, "states.csv"), "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["cell", "clone", "state", "trait"])
            for j in range(len(leaf_nodes)):
                w.writerow([f"cell_{j}", f"C{leaf_clone[j]}", leaf_state[j], f"{leaf_trait[j]:.6f}"])

        np.save(os.path.join(d, "parent.npy"), parent)
        np.save(os.path.join(d, "elen.npy"), elen)
        np.save(os.path.join(d, "leaf_nodes.npy"), np.array(leaf_nodes))
        with open(os.path.join(d, "truth.json"), "w") as f:
            json.dump(dict(scenario=SCEN, rep=made, seed=SEED0 + rep - 1,
                           n_gen=N_GEN, clones=truth_rows,
                           V_pi=float(np.var([t["pi"] for t in truth_rows])),
                           V_logk=float(np.var([np.log(t["k"]) for t in truth_rows])),
                           mean_k=float(np.mean([t["k"] for t in truth_rows]))), f, indent=1)
        made += 1
    print(f"{SCEN}: wrote {made} replicates to {OUT}")


if __name__ == "__main__":
    main()
